-- 데이터 이전 테스트용 H2(PostgreSQL 모드) 스키마: 운영 Flyway V1~V12 의 표 중 이전에 쓰는 열만 같은 이름·제약으로.
CREATE TABLE users (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    username VARCHAR(50) NOT NULL UNIQUE, password VARCHAR(100) NOT NULL, display_name VARCHAR(100) NOT NULL,
    email VARCHAR(200), department VARCHAR(100), position VARCHAR(100), role VARCHAR(20) NOT NULL DEFAULT 'USER', active BOOLEAN NOT NULL DEFAULT TRUE,
    created_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP, updated_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP);
CREATE TABLE categories (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, name VARCHAR(50) NOT NULL, parent_id BIGINT REFERENCES categories(id),
    depth SMALLINT NOT NULL CHECK (depth BETWEEN 1 AND 5), path VARCHAR(200) NOT NULL DEFAULT '', sort_order INTEGER NOT NULL DEFAULT 0,
    restricted_departments VARCHAR(1000) NOT NULL DEFAULT '',
    created_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP, updated_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP);
CREATE TABLE posts (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, title VARCHAR(300) NOT NULL, content TEXT NOT NULL, summary VARCHAR(500),
    tags VARCHAR(500) NOT NULL DEFAULT '', status VARCHAR(20) NOT NULL DEFAULT 'PUBLISHED', author_id BIGINT NOT NULL REFERENCES users(id),
    version INTEGER NOT NULL DEFAULT 1, view_count BIGINT NOT NULL DEFAULT 0,
    created_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP, updated_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    published_at TIMESTAMP WITH TIME ZONE, deleted_at TIMESTAMP WITH TIME ZONE, category_id BIGINT NOT NULL REFERENCES categories(id),
    content_format VARCHAR(20) NOT NULL DEFAULT 'MARKDOWN', pinned BOOLEAN NOT NULL DEFAULT FALSE, visibility VARCHAR(20) NOT NULL DEFAULT 'PUBLIC',
    reviewed_at TIMESTAMP WITH TIME ZONE);
CREATE TABLE post_revisions (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, post_id BIGINT NOT NULL REFERENCES posts(id) ON DELETE CASCADE, version INTEGER NOT NULL,
    title VARCHAR(300) NOT NULL, content TEXT NOT NULL, summary VARCHAR(500), category VARCHAR(300) NOT NULL, tags VARCHAR(500) NOT NULL,
    status VARCHAR(20) NOT NULL, change_type VARCHAR(20) NOT NULL, change_note VARCHAR(500), edited_by BIGINT NOT NULL REFERENCES users(id),
    created_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP, category_id BIGINT REFERENCES categories(id) ON DELETE SET NULL,
    content_format VARCHAR(20) NOT NULL DEFAULT 'MARKDOWN', visibility VARCHAR(20) NOT NULL DEFAULT 'PUBLIC', UNIQUE (post_id, version));
CREATE TABLE attachments (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, public_id VARCHAR(36) NOT NULL UNIQUE, post_id BIGINT REFERENCES posts(id) ON DELETE SET NULL,
    uploader_id BIGINT NOT NULL REFERENCES users(id), original_name VARCHAR(255) NOT NULL, stored_name VARCHAR(255) NOT NULL,
    content_type VARCHAR(150) NOT NULL, size_bytes BIGINT NOT NULL, kind VARCHAR(20) NOT NULL,
    created_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP, text_content TEXT, text_extracted_at TIMESTAMP WITH TIME ZONE,
    content_sha256 VARCHAR(64));
CREATE TABLE comments (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, post_id BIGINT NOT NULL REFERENCES posts(id) ON DELETE CASCADE,
    parent_id BIGINT REFERENCES comments(id) ON DELETE CASCADE, author_id BIGINT NOT NULL REFERENCES users(id), content TEXT NOT NULL,
    deleted_at TIMESTAMP WITH TIME ZONE, created_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP);
CREATE TABLE post_likes (
    post_id BIGINT NOT NULL REFERENCES posts(id) ON DELETE CASCADE, user_id BIGINT NOT NULL REFERENCES users(id) ON DELETE CASCADE,
    created_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP, PRIMARY KEY (post_id, user_id));
CREATE TABLE post_templates (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, name VARCHAR(100) NOT NULL, description VARCHAR(300), content TEXT NOT NULL,
    category_id BIGINT REFERENCES categories(id) ON DELETE SET NULL, tags VARCHAR(500) NOT NULL DEFAULT '', sort_order INTEGER NOT NULL DEFAULT 0,
    created_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP, updated_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP);
CREATE TABLE api_tokens (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, user_id BIGINT NOT NULL REFERENCES users(id) ON DELETE CASCADE, name VARCHAR(100) NOT NULL,
    token_hash VARCHAR(64) NOT NULL UNIQUE, token_prefix VARCHAR(16) NOT NULL, created_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    expires_at TIMESTAMP WITH TIME ZONE, last_used_at TIMESTAMP WITH TIME ZONE, revoked_at TIMESTAMP WITH TIME ZONE);
CREATE TABLE notifications (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, recipient_id BIGINT NOT NULL REFERENCES users(id) ON DELETE CASCADE,
    actor_id BIGINT REFERENCES users(id) ON DELETE CASCADE, type VARCHAR(20) NOT NULL, post_id BIGINT NOT NULL REFERENCES posts(id) ON DELETE CASCADE,
    comment_id BIGINT REFERENCES comments(id) ON DELETE CASCADE, read_at TIMESTAMP WITH TIME ZONE,
    created_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP);
CREATE TABLE post_views (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, post_id BIGINT NOT NULL REFERENCES posts(id) ON DELETE CASCADE,
    user_id BIGINT NOT NULL REFERENCES users(id) ON DELETE CASCADE, viewed_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    via VARCHAR(20) NOT NULL);
CREATE TABLE app_instance (id SMALLINT PRIMARY KEY CHECK (id = 1), instance_id VARCHAR(36) NOT NULL,
    created_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP);
CREATE TABLE data_import_map (
    source_instance VARCHAR(36) NOT NULL, entity VARCHAR(20) NOT NULL, source_key VARCHAR(64) NOT NULL, target_id BIGINT NOT NULL,
    target_key VARCHAR(64), source_version INTEGER, target_version INTEGER, source_updated_at TIMESTAMP WITH TIME ZONE,
    target_updated_at TIMESTAMP WITH TIME ZONE, applied_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    PRIMARY KEY (source_instance, entity, source_key));
CREATE TABLE data_transfers (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, direction VARCHAR(10) NOT NULL, dump_kind VARCHAR(10) NOT NULL, action VARCHAR(10) NOT NULL,
    dump_name VARCHAR(200) NOT NULL, source_instance VARCHAR(36) NOT NULL, since_at TIMESTAMP WITH TIME ZONE, exported_at TIMESTAMP WITH TIME ZONE,
    baseline BOOLEAN NOT NULL DEFAULT FALSE, status VARCHAR(20) NOT NULL, actor_id BIGINT REFERENCES users(id) ON DELETE SET NULL,
    actor_name VARCHAR(100) NOT NULL, summary VARCHAR(500), report TEXT,
    started_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP, finished_at TIMESTAMP WITH TIME ZONE);
